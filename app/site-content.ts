export type SitePriceKey = keyof typeof sitePrices;

export function formatPrice(locale: Locale, priceKey: SitePriceKey, perDay = false) {
  const amount = sitePrices[priceKey];

  if (perDay) {
    const labels: Record<Locale, string> = {
      ru: `от ${amount} € / день поездки`,
      uk: `від ${amount} € / день подорожі`,
      en: `from €${amount} / travel day`,
      es: `desde ${amount} € / día de viaje`,
    };
    return labels[locale];
  }

  const labels: Record<Locale, string> = {
    ru: `от ${amount} €`,
    uk: `від ${amount} €`,
    en: `from €${amount}`,
    es: `desde ${amount} €`,
  };
  return labels[locale];
}

